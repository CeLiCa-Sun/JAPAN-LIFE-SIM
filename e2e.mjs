import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
await page.locator('[data-tab="v68"]').waitFor();
if(await page.locator('[data-tab="v67"]').count())throw Error('Version history should be collapsed by default');
await page.getByRole('button',{name:'現場の工程・材料・人員を診断'}).click();
await page.getByRole('button',{name:'法人財務を点検'}).click();
await page.getByRole('button',{name:'NPC取引を実行'}).click();
const canvas=page.locator('#city3d');await canvas.waitFor();
const visual=await canvas.evaluate(c=>({width:c.width,height:c.height,context:!!c.getContext('webgl')}));
if(!visual.width||!visual.height)throw Error('Invalid 3D canvas');
await page.locator('#toggle-legacy').click();
await page.locator('[data-tab="v67"]').waitFor();
await page.locator('[data-tab="v67"]').click();
await page.getByRole('button',{name:'契約・設備・人員を更新'}).click();
await page.locator('[data-tab="sector"]').click();
await page.locator('#company').selectOption({index:1});
await page.locator('[data-tab="history"]').click();
page.on('dialog',d=>d.accept());
await page.locator('#save').click();
await page.locator('#load').click();
if(errors.length)throw Error('Browser errors: '+errors.join('; '));
console.log('Ver6.8 Chromium E2E passed',JSON.stringify(visual));
await browser.close();
