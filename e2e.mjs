import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true,args:['--enable-webgl','--use-gl=angle','--use-angle=swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765/',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:/JAPAN-LIFE-SIM/}).waitFor();
await page.locator('[data-tab="v60"]').click();
await page.getByRole('button',{name:'業種経営指標を集計'}).click();
await page.getByText('進行中').first().waitFor();
await page.locator('[data-tab="history"]').click();
await page.locator('#save').click();page.once('dialog',d=>d.accept());
await page.locator('#load').click();page.once('dialog',d=>d.accept());
await page.locator('[data-tab="v55"]').click();
const canvas=page.locator('#city3d');await canvas.waitFor();
const result=await canvas.evaluate(c=>({width:c.width,context:!!c.getContext('webgl')}));
if(!result.width)throw Error('3D canvas has no dimensions');
if(errors.length)throw Error('Browser JS errors: '+errors.join('; '));
console.log('Browser E2E passed:',JSON.stringify(result));
await browser.close();
